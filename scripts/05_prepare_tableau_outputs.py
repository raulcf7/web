def write_data_dictionary(output_files: list[str]) -> None:
    lines = [
        "# Tableau Data Dictionary",
        "",
        "This dictionary documents the final Tableau-facing CSVs after `scripts/05_prepare_tableau_outputs.py` has standardized column names and metadata.",
        "",
    ]
    for file_name in output_files:
        path = OUTPUTS / file_name
        fields, rows = read_csv(path)
        if not fields:
            continue
        lines.extend(
            [
                f"## {file_name}",
                f"- **Granularity:** {file_granularity(file_name)}",
                "",
                "| column | type | description | recommended_tableau_use |",
                "|---|---|---|---|",
            ]
        )
        for field in fields:
            values = [row.get(field, "") for row in rows]
            lines.append(f"| `{field}` | {infer_type(values)} | {description_for_column(field)} | {tableau_use_for_column(field)} |")
        lines.append("")
    (DOCS / "tableau_data_dictionary.md").write_text("\n".join(lines), encoding="utf-8")


