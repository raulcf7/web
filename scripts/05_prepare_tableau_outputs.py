def priority_level(metric_name: str, file_name: str = "") -> str:
    metric = metric_name.lower()
    file_name = file_name.lower()
    high_tokens = [
        "field_tilt",
        "possession_proxy",
        "shots",
        "xg",
        "threat",
        "box_entries",
        "danger",
        "progressive_passes",
        "dangerous_losses",
        "momentum",
        "team_width",
        "team_depth",
        "compactness",
    ]
    if "insight" in file_name:
        return "high"
    if any(token in metric for token in high_tokens):
        return "high"
    if any(token in metric for token in ["total_actions", "minutes", "distance", "speed", "sequence"]):
        return "medium"
    return "medium"


def add_tableau_metadata(rows: list[dict[str, Any]], file_name: str) -> list[dict[str, Any]]:
    out = []
    for row in rows:
        clean = {snake_case(k): clean_cell(v) for k, v in row.items()}
        metric = first_non_blank(clean.get("metric_name"), clean.get("insight_type"), clean.get("primary_profile"), file_name)
        clean.setdefault("metric_unit", metric_unit(metric))
        clean.setdefault("interpretation_label", "")
        clean.setdefault("insight_text", "")
        clean["dashboard_section"] = first_non_blank(clean.get("dashboard_section"), dashboard_section(metric, file_name))
        clean["recommended_chart_type"] = first_non_blank(clean.get("recommended_chart_type"), recommended_chart_type(file_name, metric))
        clean["priority_level"] = first_non_blank(clean.get("priority_level"), priority_level(metric, file_name))
        out.append(clean)
    return out


