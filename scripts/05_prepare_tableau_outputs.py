def snake_case(name: str) -> str:
    value = re.sub(r"[^0-9A-Za-z]+", "_", str(name).strip())
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    value = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", value)
    value = re.sub(r"_+", "_", value).strip("_").lower()
    return value or "unnamed"


def unique_names(names: list[str]) -> list[str]:
    seen: dict[str, int] = {}
    result = []
    for name in names:
        base = snake_case(name)
        count = seen.get(base, 0)
        seen[base] = count + 1
        result.append(base if count == 0 else f"{base}_{count + 1}")
    return result


def read_csv(path: Path, normalize_headers: bool = True) -> tuple[list[str], list[dict[str, str]]]:
    if not path.exists():
        return [], []
    with path.open("r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.reader(handle)
        try:
            header = next(reader)
        except StopIteration:
            return [], []
        fields = unique_names(header) if normalize_headers else header
        rows: list[dict[str, str]] = []
        for raw in reader:
            row = {}
            for idx, field in enumerate(fields):
                row[field] = clean_cell(raw[idx]) if idx < len(raw) else ""
            rows.append(row)
    return fields, rows


def write_csv(path: Path, fields: list[str], rows: list[dict[str, Any]]) -> None:
    fields = unique_names(fields)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: clean_cell(row.get(field, "")) for field in fields})


def clean_cell(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            return ""
        return f"{value:.4f}".rstrip("0").rstrip(".")
    text = str(value).strip()
    text = re.sub(r"\s+", " ", text)
    return text


def num(value: Any) -> float | None:
    if value in ("", None):
        return None
    try:
        number = float(str(value).replace("%", "").replace(",", ""))
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def truthy(value: Any) -> bool:
    return str(value).strip().lower() == "true"


def safe_round(value: Any, digits: int = 4) -> float | str:
    number = num(value)
    if number is None:
        return ""
    return round(number, digits)


def is_action(row: dict[str, str]) -> bool:
    return row.get("is_blank_event") != "true" and bool(row.get("team_name"))


def is_pass(row: dict[str, str]) -> bool:
    return row.get("coord_source") == "pass_loc" or bool(row.get("passer_id"))


def is_completed(row: dict[str, str]) -> bool:
    return truthy(row.get("raw_completed")) or row.get("outcome") == "completed_pass"


def is_shot(row: dict[str, str]) -> bool:
    return bool(row.get("shooter_id")) or bool(row.get("shot_outcome")) or row.get("coord_source") == "shot_loc"


def is_shot_row_preferred(row: dict[str, str]) -> bool:
    return bool(row.get("shooter_id")) or row.get("coord_source") == "shot_loc"


def is_shot_on_target(row: dict[str, str]) -> bool:
    outcome = row.get("shot_outcome") or row.get("raw_shot_outcome")
    return outcome in {"goal", "save"}


def is_goal(row: dict[str, str]) -> bool:
    return row.get("shot_outcome") == "goal" or row.get("raw_shot_outcome") == "goal" or truthy(row.get("raw_is_scored"))


def is_final_third(row: dict[str, str]) -> bool:
    x = num(row.get("x_oriented"))
    return x is not None and x > FINAL_THIRD_X


def ends_final_third(row: dict[str, str]) -> bool:
    x = num(row.get("end_x_oriented"))
    return x is not None and x > FINAL_THIRD_X


def is_box(row: dict[str, str]) -> bool:
    x = num(row.get("x_oriented"))
    y = abs(num(row.get("y_oriented")) or 999)
    end_x = num(row.get("end_x_oriented"))
    end_y = abs(num(row.get("end_y_oriented")) or 999)
    start_box = x is not None and x >= BOX_X and y <= BOX_HALF_WIDTH
    end_box = end_x is not None and end_x >= BOX_X and end_y <= BOX_HALF_WIDTH
    return start_box or end_box or truthy(row.get("is_box"))


def vertical_gain(row: dict[str, str]) -> float:
    start = num(row.get("x_oriented"))
    end = num(row.get("end_x_oriented"))
    if start is None or end is None:
        return 0.0
    return max(0.0, end - start)


def is_progressive(row: dict[str, str]) -> bool:
    return is_completed(row) and vertical_gain(row) >= PROGRESSIVE_GAIN_M


def is_recovery(row: dict[str, str]) -> bool:
    labels = {
        row.get("start_type"),
        row.get("turnover_type"),
        row.get("outcome"),
        row.get("raw_interception_type"),
    }
    return bool(labels & {"recovery", "interception", "tackle", "shot_recovered", "anticipated", "reacted", "passive"})


def is_loss(row: dict[str, str]) -> bool:
    return truthy(row.get("is_turnover")) or row.get("outcome") in {"turnover", "ball_lost", "lost_ball"}


def threat_weight(x: float | None, y: float | None) -> float:
    if x is None:
        return 0.0
    abs_y = abs(y if y is not None else 99.0)
    if x >= BOX_X and abs_y <= BOX_HALF_WIDTH:
        return 0.18
    if x > FINAL_THIRD_X:
        return 0.08
    if x >= -FINAL_THIRD_X:
        return 0.03
    return 0.01


def threat_value(row: dict[str, str]) -> float:
    xg = num(row.get("xg"))
    if is_shot(row) and xg is not None:
        return xg
    start_x = num(row.get("x_oriented"))
    start_y = num(row.get("y_oriented"))
    end_x = num(row.get("end_x_oriented"))
    end_y = num(row.get("end_y_oriented"))
    if end_x is None:
        return 0.0
    return max(0.0, threat_weight(end_x, end_y) - threat_weight(start_x, start_y))


def first_non_blank(*values: Any) -> str:
    for value in values:
        text = clean_cell(value)
        if text:
            return text
    return ""


def metric_unit(metric_name: str) -> str:
    metric = metric_name.lower()
    if metric.endswith("_per_90") or "per_90" in metric:
        return "per_90"
    if any(token in metric for token in ["share", "rate", "pct", "percentage", "field_tilt", "possession_proxy", "completion"]):
        return "share"
    if any(token in metric for token in ["xg", "threat", "danger_index", "momentum_index"]):
        return "index"
    if any(token in metric for token in ["distance", "width", "depth", "height", "compactness", "gained"]):
        return "meters"
    if any(token in metric for token in ["speed", "velocity"]):
        return "m_per_s"
    if any(token in metric for token in ["duration", "second"]):
        return "seconds"
    if "minute" in metric:
        return "minutes"
    return "count"


def dashboard_section(metric_name: str, file_name: str = "") -> str:
    metric = metric_name.lower()
    file_name = file_name.lower()
    if "player" in file_name:
        return "Player Impact"
    if "tracking" in file_name:
        return "Tracking & Team Shape"
    if "shot" in file_name or any(token in metric for token in ["shot", "xg", "threat", "danger", "box", "key_pass"]):
        return "Chance Creation & Final Third"
    if any(token in metric for token in ["loss", "recovery", "interception", "tackle", "ppda", "press"]):
        return "Defensive Behaviour & Transitions"
    if any(token in metric for token in ["progressive", "vertical", "sequence", "directness", "entry"]):
        return "Territory & Control"
    if any(token in metric for token in ["field_tilt", "possession", "territory", "action_height", "attacking_third"]):
        return "Territory & Control"
    if "momentum" in file_name:
        return "Executive Match Overview"
    if "insight" in file_name:
        return "Executive Match Overview"
    return "Executive Match Overview"


def recommended_chart_type(file_name: str, metric_name: str = "") -> str:
    file_name = file_name.lower()
    metric = metric_name.lower()
    if "event_map" in file_name:
        return "pitch scatter map"
    if "shots" in file_name:
        return "shot map"
    if "zone" in file_name:
        return "pitch heatmap"
    if "period" in file_name:
        return "grouped bar chart"
    if "momentum" in file_name:
        return "dual-axis timeline"
    if "player_profiles" in file_name:
        return "profile table"
    if "player_metrics" in file_name:
        return "ranked bar chart"
    if "possession" in file_name:
        return "sequence table and scatter"
    if "tracking_team_shape" in file_name:
        return "time-series line chart"
