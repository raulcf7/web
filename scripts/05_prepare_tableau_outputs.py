def infer_type(values: list[str]) -> str:
    sample = [value for value in values if value != ""][:50]
    if not sample:
        return "string"
    numeric = sum(num(value) is not None for value in sample)
    booleans = sum(value.lower() in {"true", "false"} for value in sample)
    if booleans == len(sample):
        return "boolean"
    if numeric == len(sample):
        return "number"
    return "string"


