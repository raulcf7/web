def write_standardized_existing(file_name: str) -> None:
    path = OUTPUTS / file_name
    fields, rows = read_csv(path)
    if not rows:
        return
    rows = add_tableau_metadata(rows, file_name)
    all_fields = sorted({field for row in rows for field in row})
    write_csv(path, preferred_field_order(all_fields), rows)


def load_events() -> list[dict[str, str]]:
    _, events = read_csv(EVENTS_FILE)
    return [row for row in events if is_action(row)]


def load_team_lookup() -> dict[str, str]:
    _, games = read_csv(GAMES_FILE)
    lookup: dict[str, str] = {}
    for game in games:
        home_id = game.get("home_team_id")
        away_id = game.get("away_team_id")
        if home_id and away_id:
            lookup[home_id] = game.get("away_team_name", "")
            lookup[away_id] = game.get("home_team_name", "")
    return lookup


def infer_event_type(row: dict[str, str]) -> str:
    if is_shot(row):
        return "shot"
    if is_pass(row):
        return "pass"
    if is_recovery(row):
        return "recovery"
    if is_loss(row):
        return "loss"
    return first_non_blank(row.get("outcome"), row.get("phase_type"), row.get("start_type"), row.get("coord_source"), "event")


def event_interpretation(row: dict[str, str], event_type: str) -> str:
    if event_type == "shot":
        return "shot attempt"
    if is_box(row):
        return "box involvement"
    if ends_final_third(row):
        return "final-third entry"
    if is_progressive(row):
        return "progressive action"
    if event_type == "loss":
        return "turnover / loss"
    if event_type == "recovery":
        return "ball recovery"
    return "context event"


def event_dashboard_section(row: dict[str, str], event_type: str) -> str:
    if event_type == "shot" or is_box(row):
        return "Chance Creation & Final Third"
    if event_type in {"loss", "recovery"}:
        return "Defensive Behaviour & Transitions"
    if is_progressive(row) or ends_final_third(row) or is_final_third(row):
        return "Territory & Control"
    return "Executive Match Overview"


def event_priority(row: dict[str, str], event_type: str) -> str:
    if event_type == "shot" or is_box(row) or is_loss(row):
        return "high"
    if is_progressive(row) or ends_final_third(row) or is_recovery(row):
        return "medium"
    return "low"


def build_event_map(events: list[dict[str, str]], opponent_lookup: dict[str, str]) -> None:
    rows: list[dict[str, Any]] = []
    for row in events:
        x = num(row.get("x_oriented"))
        y = num(row.get("y_oriented"))
        if x is None or y is None:
            continue
        event_type = infer_event_type(row)
        relevant = (
            event_type in {"shot", "pass", "recovery", "loss"}
            or is_box(row)
            or is_final_third(row)
            or ends_final_third(row)
            or is_progressive(row)
            or truthy(row.get("is_set_play"))
        )
        if not relevant:
            continue
        label = event_interpretation(row, event_type)
        team = row.get("team_name", "")
        rows.append(
            {
                "match_id": row.get("match_id", ""),
                "game_id_opta": row.get("game_id_opta", ""),
                "event_id": row.get("event_id", ""),
                "order": row.get("order", ""),
                "period": row.get("period", ""),
                "period_second": safe_round(row.get("period_second")),
                "match_second": safe_round(row.get("match_second")),
                "match_minute": row.get("match_minute", ""),
                "minute_bin_5": row.get("minute_bin_5", ""),
                "team_id": row.get("team_id", ""),
                "team_name": team,
                "opponent_team_id": row.get("opponent_team_id", ""),
                "opponent_team_name": first_non_blank(row.get("opponent_team_name"), opponent_lookup.get(row.get("team_id", ""))),
                "player_id": first_non_blank(row.get("player_id"), row.get("passer_id"), row.get("shooter_id")),
                "player_name": row.get("player_name", ""),
                "event_type": event_type,
                "outcome": first_non_blank(row.get("outcome"), row.get("shot_outcome"), row.get("raw_outcome")),
                "phase": first_non_blank(row.get("phase_type"), row.get("state"), row.get("start_type")),
                "third": row.get("third", ""),
                "zone": row.get("third", ""),
                "channel": row.get("channel", ""),
                "x": safe_round(row.get("x")),
                "y": safe_round(row.get("y")),
                "end_x": safe_round(row.get("end_x")),
                "end_y": safe_round(row.get("end_y")),
                "x_oriented": round(x, 4),
                "y_oriented": round(y, 4),
                "end_x_oriented": safe_round(row.get("end_x_oriented")),
                "end_y_oriented": safe_round(row.get("end_y_oriented")),
                "is_progressive": is_progressive(row),
                "is_final_third_entry": ends_final_third(row) and not is_final_third(row),
                "is_box_entry": is_box(row),
                "is_set_play": truthy(row.get("is_set_play")),
                "xg": safe_round(row.get("xg")),
                "threat_value": round(threat_value(row), 4),
                "interpretation_label": label,
                "insight_text": f"{team} {label} at minute {row.get('match_minute', '')}.",
                "dashboard_section": event_dashboard_section(row, event_type),
                "recommended_chart_type": "pitch scatter map",
                "priority_level": event_priority(row, event_type),
            }
        )
    rows = add_tableau_metadata(rows, "tableau_event_map.csv")
    fields = preferred_field_order(sorted({field for item in rows for field in item}))
    write_csv(OUTPUTS / "tableau_event_map.csv", fields, rows)


def build_shots(events: list[dict[str, str]], opponent_lookup: dict[str, str]) -> None:
    preferred = [row for row in events if is_shot_row_preferred(row)]
    if not preferred:
        preferred = [row for row in events if is_shot(row)]

    rows: list[dict[str, Any]] = []
    seen: set[tuple[str, str, str, str, str]] = set()
    for row in preferred:
        shot_key = (
            row.get("match_id", ""),
            row.get("team_name", ""),
            first_non_blank(row.get("shooter_id"), row.get("player_id")),
            f"{num(row.get('match_second')) or 0:.1f}",
            f"{num(row.get('xg')) or 0:.4f}",
        )
        if shot_key in seen:
            continue
        seen.add(shot_key)
        team = row.get("team_name", "")
        outcome = first_non_blank(row.get("shot_outcome"), row.get("raw_shot_outcome"), row.get("outcome"), "unknown")
        xg = num(row.get("xg")) or 0.0
        label = "high-value shot" if xg >= 0.12 else "medium-value shot" if xg >= 0.05 else "low-value shot"
        rows.append(
            {
                "match_id": row.get("match_id", ""),
                "game_id_opta": row.get("game_id_opta", ""),
                "event_id": row.get("event_id", ""),
                "period": row.get("period", ""),
                "period_second": safe_round(row.get("period_second")),
                "match_second": safe_round(row.get("match_second")),
                "match_minute": row.get("match_minute", ""),
                "minute_bin_5": row.get("minute_bin_5", ""),
                "team_id": row.get("team_id", ""),
                "team_name": team,
                "opponent_team_id": row.get("opponent_team_id", ""),
                "opponent_team_name": first_non_blank(row.get("opponent_team_name"), opponent_lookup.get(row.get("team_id", ""))),
                "player_id": first_non_blank(row.get("shooter_id"), row.get("player_id"), row.get("raw_shooter_id")),
                "player_name": row.get("player_name", ""),
                "event_type": "shot",
                "outcome": outcome,
                "shot_outcome": outcome,
                "is_goal": is_goal(row),
                "is_on_target": is_shot_on_target(row),
                "is_from_box": is_box(row),
                "xg": round(xg, 4),
                "shot_distance_m": safe_round(first_non_blank(row.get("raw_goal_dist"), row.get("raw_goal_distance"))),
                "shot_angle": safe_round(row.get("raw_angle")),
                "shot_technique": row.get("raw_shot_technique", ""),
                "set_play_type": row.get("set_play_type") or row.get("raw_shot_set_piece"),
                "phase": first_non_blank(row.get("phase_type"), row.get("start_type"), row.get("state")),
                "third": row.get("third", ""),
                "zone": first_non_blank(row.get("raw_shot_zone"), row.get("third")),
                "channel": row.get("channel", ""),
                "x_oriented": safe_round(row.get("x_oriented")),
                "y_oriented": safe_round(row.get("y_oriented")),
                "interpretation_label": label,
                "insight_text": f"{team} generated a {xg:.2f} xG shot ({outcome}) in minute {row.get('match_minute', '')}.",
            }
        )
    rows = add_tableau_metadata(rows, "tableau_shots.csv")
    fields = preferred_field_order(sorted({field for item in rows for field in item}))
    write_csv(OUTPUTS / "tableau_shots.csv", fields, rows)


def possession_attack_type(duration: float, actions: int, gain: float, shots: int, box_entries: int) -> str:
    if shots or box_entries:
        if duration <= 12 and gain >= 25:
            return "direct transition"
        return "chance-ending possession"
    if duration <= 10 and gain >= 20:
        return "direct attack"
    if actions >= 12 or duration >= 35:
        return "elaborate possession"
    if gain >= 20:
        return "progressive possession"
    return "maintenance possession"


def build_possession_sequences(events: list[dict[str, str]], opponent_lookup: dict[str, str]) -> None:
    grouped: dict[tuple[str, str, str], list[dict[str, str]]] = defaultdict(list)
    for row in events:
        poss_id = row.get("poss_id")
        if not poss_id:
            continue
        grouped[(row.get("match_id", ""), row.get("period", ""), poss_id)].append(row)

    rows: list[dict[str, Any]] = []
    for (match_id, period, poss_id), poss_events in grouped.items():
        poss_events.sort(key=lambda item: (num(item.get("match_second")) or 0.0, num(item.get("order")) or 0.0))
        team_counts = Counter(row.get("team_name", "") for row in poss_events if row.get("team_name"))
        if not team_counts:
            continue
        team = team_counts.most_common(1)[0][0]
        team_rows = [row for row in poss_events if row.get("team_name") == team]
        seconds = [num(row.get("match_second")) for row in team_rows if num(row.get("match_second")) is not None]
        if not seconds:
            continue
        start_second = min(seconds)
        end_second = max(seconds)
        duration = max(0.0, end_second - start_second)
        shots = sum(1 for row in team_rows if is_shot(row))
        shot_xg = sum(num(row.get("xg")) or 0.0 for row in team_rows if is_shot(row))
        final_entries = sum(1 for row in team_rows if ends_final_third(row) and not is_final_third(row))
        box_entries = sum(1 for row in team_rows if is_box(row))
        progressive_actions = sum(1 for row in team_rows if is_progressive(row))
        vertical_gain_m = sum(vertical_gain(row) for row in team_rows)
        threat = sum(threat_value(row) for row in team_rows)
        start_x_values = [num(row.get("x_oriented")) for row in team_rows if num(row.get("x_oriented")) is not None]
        end_x_values = [num(row.get("end_x_oriented")) for row in team_rows if num(row.get("end_x_oriented")) is not None]
        phase_counts = Counter(row.get("phase_type", "") for row in team_rows if row.get("phase_type"))
        start_type = first_non_blank(*(row.get("start_type") for row in team_rows[:5]))
        attack_type = possession_attack_type(duration, len(team_rows), vertical_gain_m, shots, box_entries)
        rows.append(
            {
                "match_id": match_id,
                "poss_id": poss_id,
                "team_name": team,
                "opponent_team_name": first_non_blank(opponent_lookup.get(team), next((row.get("opponent_team_name") for row in team_rows if row.get("opponent_team_name")), "")),
                "period": period,
                "start_match_second": round(start_second, 4),
                "end_match_second": round(end_second, 4),
                "duration_seconds": round(duration, 4),
                "start_minute": int(start_second // 60) + 1,
                "minute_bin_5": int(start_second // 300) * 5,
                "actions": len(team_rows),
                "passes": sum(1 for row in team_rows if is_pass(row)),
                "progressive_actions": progressive_actions,
                "vertical_gain_m": round(vertical_gain_m, 4),
                "start_x_oriented": round(start_x_values[0], 4) if start_x_values else "",
                "end_x_oriented": round(end_x_values[-1], 4) if end_x_values else "",
                "final_third_entries": final_entries,
                "box_entries": box_entries,
                "shots": shots,
                "xg": round(shot_xg, 4),
                "threat_value": round(threat, 4),
                "dominant_phase": phase_counts.most_common(1)[0][0] if phase_counts else "",
                "start_type": start_type,
                "attack_type": attack_type,
                "interpretation_label": attack_type,
                "insight_text": f"{team} possession lasted {duration:.1f}s, gained {vertical_gain_m:.1f}m and produced {shots} shots.",
            }
        )

    rows = add_tableau_metadata(rows, "tableau_possession_sequences.csv")
    fields = preferred_field_order(sorted({field for item in rows for field in item}))
    write_csv(OUTPUTS / "tableau_possession_sequences.csv", fields, rows)


